# 05 — Final da linha
# Objetivo: Construir uma linha com mais de uma instrução.
# Pré-requisitos: exemplos anteriores deste tópico e tópicos anteriores.
# Observe: end substitui a quebra de linha final de print.
# Como estudar: preveja a saída, execute e altere um valor por vez.
# Execução guiada: este exemplo não solicita entrada.
# Confira na saída: 'Curso: ALP'

# O primeiro print deixa o cursor na mesma linha.
print("Curso: ", end="")
print("ALP")
# Um espaço no end impede que as palavras fiquem coladas.
print("Estudar", end=" ")
print("e praticar")
# Um print sem argumentos produz apenas uma linha vazia.
print()
print("Fim da apresentação.")
