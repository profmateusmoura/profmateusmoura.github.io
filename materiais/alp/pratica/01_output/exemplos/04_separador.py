# 04 — Separador de saída
# Objetivo: Personalizar a separação entre argumentos.
# Pré-requisitos: exemplos anteriores deste tópico e tópicos anteriores.
# Observe: sep altera o texto inserido entre os argumentos de print.
# Como estudar: preveja a saída, execute e altere um valor por vez.
# Execução guiada: este exemplo não solicita entrada.
# Confira na saída: 'ALP | Python | Início'

# Sem sep explícito, a separação seria um espaço.
print("ALP", "Python", "Início", sep=" | ")
# Aqui a mesma função produz uma data visual, sem calcular nada.
print("23", "10", "2026", sep="/")
print("A", "L", "P", sep="")
