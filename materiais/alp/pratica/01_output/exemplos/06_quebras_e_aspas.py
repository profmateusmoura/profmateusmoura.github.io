# 06 — Quebras e aspas
# Objetivo: Representar caracteres especiais em textos.
# Pré-requisitos: exemplos anteriores deste tópico e tópicos anteriores.
# Observe: \n representa uma quebra; aspas diferentes podem delimitar uma frase.
# Como estudar: preveja a saída, execute e altere um valor por vez.
# Execução guiada: este exemplo não solicita entrada.
# Confira na saída: 'Segunda linha'

# O texto abaixo contém uma quebra de linha dentro de um único print.
print("Primeira linha\nSegunda linha")
# Aspas simples externas permitem aspas duplas no conteúdo.
print('O professor disse: "pratique".')
# A barra invertida permite representar aspas do mesmo tipo.
print("Ela respondeu: \"vou tentar\".")
