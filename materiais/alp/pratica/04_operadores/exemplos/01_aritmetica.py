# 01 — Operações aritméticas
# Objetivo: Aplicar soma, subtração, produto e divisão.
# Pré-requisitos: exemplos anteriores deste tópico e tópicos anteriores.
# Observe: A divisão / produz float mesmo com operandos inteiros.
# Como estudar: preveja a saída, execute e altere um valor por vez.
# Execução guiada: este exemplo não solicita entrada.
# Confira na saída: 'Divisão: 2.4'

a = 12
b = 5
# Cada expressão calcula um novo valor sem alterar a e b.
print("Soma:", a + b)
print("Diferença:", a - b)
print("Produto:", a * b)
print("Divisão:", a / b)
# O sinal - antes de um valor é um operador que troca seu sinal.
print("Oposto de a:", -a)
