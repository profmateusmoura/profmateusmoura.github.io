# 01 — Quatro tipos escalares
# Objetivo: Identificar tipos sem coleções.
# Pré-requisitos: exemplos anteriores deste tópico e tópicos anteriores.
# Observe: type informa o tipo do valor atualmente associado ao nome.
# Como estudar: preveja a saída, execute e altere um valor por vez.
# Execução guiada: este exemplo não solicita entrada.
# Confira na saída: "<class 'bool'>"

# = associa o valor da direita ao nome da esquerda: é atribuição.
# Neste tópico apenas guardamos, copiamos e exibimos valores, sem contas.
# int: contagem inteira; float: valor com parte fracionária.
quantidade = 4
temperatura = 23.5
# str: texto simples; bool: verdadeiro ou falso.
curso = "ALP"
ativo = True
print(quantidade, type(quantidade))
print(temperatura, type(temperatura))
print(curso, type(curso))
print(ativo, type(ativo))
